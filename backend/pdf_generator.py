# ── Helpers ───────────────────────────────────────────────────────────────────
def fmtv(v, t="currency"):
    if v is None: return "—"
    try: v = float(v)
    except: return str(v) if v else "—"
    if math.isnan(v) or math.isinf(v): return "—"
    if t == "currency":
        if abs(v) >= 1e12: return f"${v/1e12:.2f}T"
        if abs(v) >= 1e9:  return f"${v/1e9:.2f}B"
        if abs(v) >= 1e6:  return f"${v/1e6:.2f}M"
        return f"${v:.2f}"
    if t == "pct":   return f"{v*100:.1f}%"
    if t == "x":     return f"{v:.1f}x"
    if t == "price": return f"${v:.2f}"
    if t == "ratio": return f"{v:.2f}"
    return str(v)

def vc(verdict):
    return GREEN2 if verdict=="Undervalued" else RED2 if verdict=="Overvalued" else YELLOW2

def uc(pct):
    if pct is None: return GREY3
    return GREEN2 if pct > 0 else RED2

