# ── Cover drawn via canvas on first page ──────────────────────────────────────
def draw_cover(canv, doc, data):
    co = data.get("consensus") or {}
    km = data.get("key_metrics") or {}
    an = data.get("analyst") or {}

    # Full bleed background
    canv.setFillColor(NAVY)
    canv.rect(0, 0, W, H, fill=1, stroke=0)

    # Left accent stripe
    canv.setFillColor(BLUE2)
    canv.rect(0, 0, 3*mm, H, fill=1, stroke=0)

    # Subtle grid
    canv.setStrokeColor(colors.HexColor("#111827"))
    canv.setLineWidth(0.4)
    for x in range(0, int(W)+1, 38):
        canv.line(x, 0, x, H)
    for y in range(0, int(H)+1, 38):
        canv.line(0, y, W, y)

    # Equity Valuation badge
    canv.setFillColor(BLUE2)
    canv.roundRect(MARGIN, H-50*mm, 42*mm, 12*mm, 2*mm, fill=1, stroke=0)
    canv.setFont("Helvetica-Bold", 9); canv.setFillColor(WHITE)
    canv.drawString(MARGIN+4*mm, H-44*mm, "Equity Valuation")
    canv.setFont("Helvetica", 7); canv.setFillColor(GREY2)
    canv.drawString(MARGIN+4*mm, H-48.5*mm, "Equity Research Platform")

    # Date
    canv.setFont("Helvetica", 7); canv.setFillColor(GREY3)
    canv.drawRightString(W-MARGIN, H-43*mm,
        datetime.datetime.now().strftime("%d %B %Y"))

    # Company name
    name = data.get("company_name","")
    y = H - 88*mm
    font_size = 28
    while canv.stringWidth(name, "Helvetica-Bold", font_size) > INNER and font_size > 16:
        font_size -= 1
    canv.setFont("Helvetica-Bold", font_size); canv.setFillColor(WHITE)
    canv.drawString(MARGIN, y, name)

    # Badges row
    y -= 13*mm
    # Ticker badge
    tw = max(canv.stringWidth(data.get("ticker",""), "Helvetica-Bold", 9) + 14, 22*mm)
    canv.setFillColor(BLUE2)
    canv.roundRect(MARGIN, y-2*mm, tw, 8*mm, 1.5*mm, fill=1, stroke=0)
    canv.setFont("Helvetica-Bold", 9); canv.setFillColor(WHITE)
    canv.drawCentredString(MARGIN+tw/2, y+1.5*mm, data.get("ticker",""))
    # Sector badge
    sector = data.get("sector","")
    if sector:
        sw = canv.stringWidth(sector, "Helvetica", 7.5) + 14
        bx = MARGIN + tw + 4*mm
        canv.setFillColor(colors.HexColor("#1e2d5a"))
        canv.roundRect(bx, y-2*mm, sw, 8*mm, 1.5*mm, fill=1, stroke=0)
        canv.setFont("Helvetica", 7.5); canv.setFillColor(GREY2)
        canv.drawCentredString(bx+sw/2, y+1.5*mm, sector)

    # Divider
    y -= 13*mm
    canv.setStrokeColor(colors.HexColor("#1e3a6e"))
    canv.setLineWidth(1)
    canv.line(MARGIN, y, W-MARGIN, y)

    # Key stats strip
    y -= 20*mm
    stats = [
        ("Current Price",    fmtv(data.get("current_price"), "price")),
        ("Market Cap",       fmtv(km.get("market_cap") or data.get("market_cap"), "currency")),
        ("Intrinsic Value",  fmtv(co.get("average_intrinsic_value"), "price")),
        ("Upside / Down",    f"{'+' if (co.get('upside_pct') or 0)>0 else ''}{co.get('upside_pct') or '—'}%"),
        ("Models Applied",   str(co.get("models_used","—"))),
        ("Recommendation",   (an.get("recommendation") or "—").replace("_"," ").title()),
    ]
    col = INNER / len(stats)
    for i, (lbl, val) in enumerate(stats):
        x = MARGIN + i*col
        text_color = WHITE
        if lbl == "Upside / Down":
            pct = co.get("upside_pct")
            text_color = GREEN2 if pct and pct>0 else RED2 if pct else WHITE
        canv.setFont("Helvetica-Bold", 13); canv.setFillColor(text_color)
        canv.drawString(x, y, val)
        canv.setFont("Helvetica", 6); canv.setFillColor(GREY3)
        canv.drawString(x, y-5.5*mm, lbl.upper())

    # Verdict box
    verdict = co.get("overall_verdict","")
    y -= 30*mm
    vcolor = vc(verdict)
    canv.setFillColor(vcolor)
    canv.roundRect(MARGIN, y-5*mm, 52*mm, 13*mm, 2*mm, fill=1, stroke=0)
    canv.setFont("Helvetica-Bold", 11); canv.setFillColor(WHITE)
    canv.drawCentredString(MARGIN+26*mm, y+0.5*mm, verdict.upper() if verdict else "—")

    # Description
    desc = (data.get("description") or "")[:380]
    if desc:
        y -= 22*mm
        canv.setFont("Helvetica", 7.5); canv.setFillColor(GREY3)
        words = desc.split(); line = []; lines2 = []
        for w in words:
            test = " ".join(line+[w])
            if canv.stringWidth(test,"Helvetica",7.5) < INNER:
                line.append(w)
            else:
                if line: lines2.append(" ".join(line))
                line = [w]
            if len(lines2) >= 4: break
        if line and len(lines2)<4: lines2.append(" ".join(line))
        for i,ln in enumerate(lines2[:4]):
            canv.drawString(MARGIN, y-i*5*mm, ln)

    # Footer watermark
    canv.setFont("Helvetica", 5.5); canv.setFillColor(colors.HexColor("#1e2a4a"))
    canv.drawString(MARGIN, 12*mm,
        "FOR INFORMATIONAL PURPOSES ONLY  ·  NOT INVESTMENT ADVICE  ·  EQUITY VALUATION EQUITY RESEARCH")

