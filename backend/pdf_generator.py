def dcf_sensitivity_table(data):
    sens = data.get("dcf_sensitivity")
    if not sens: return None
    price   = data.get("current_price") or 0
    waccs   = sens.get("waccs",[])
    growths = sens.get("growths",[])
    table   = sens.get("table",[])
    header  = [Paragraph("Growth \\ WACC", TS["th"])] + [Paragraph(w, TS["th"]) for w in waccs]
    rows    = [header]
    for gi, g in enumerate(growths):
        row = [Paragraph(g, TS["tdb"])]
        for val in table[gi]:
            pct = (val-price)/price if price else 0
            tc = GREEN2 if pct>0.15 else RED2 if pct<-0.15 else YELLOW2
            row.append(Paragraph(f"${val}", ParagraphStyle("sv",parent=TS["tdb"],textColor=tc)))
        rows.append(row)
    cw = INNER/(len(waccs)+1)
    t = Table(rows, colWidths=[cw*1.2]+[cw*0.93]*len(waccs))
    t.setStyle(tbl_style([("ALIGN",(1,0),(-1,-1),"CENTER")]))
    return t

